#!/usr/bin/env node
// Generates a short video from a still with Gemini Omni Flash (the Gemini
// API's video model since Veo was retired), via the Interactions API.
//
//   node scripts/generate-video.mjs --name hero-loop --from art/generated/video-start-1.png \
//     --loop --duration 8 --count 2 --prompt "…"
//   node scripts/generate-video.mjs --name hero-loop-night --edit art/generated/hero-loop-2.mp4 \
//     --prompt "Change only the lighting to …"
//
// --loop passes the start image as both first and last frame, so the clip
// loops seamlessly (two-frame interpolation allows 3–10 s).
// Results land in art/generated/ (gitignored). Audio is generated by the
// model and stripped later when encoding for the web.
//
// Needs GEMINI_API_KEY, found the same way as generate-art.mjs.
// Cost (Nov 2026): about $0.07 per second at 720p, $0.10 at 1080p.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { parseArgs } from "node:util"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const OUT_DIR = join(ROOT, "art/generated")
const MODEL = process.env.GEMINI_VIDEO_MODEL ?? "gemini-omni-1.2-flash"
const API = "https://generativelanguage.googleapis.com/v1beta"

function loadKey() {
  if (process.env.GEMINI_API_KEY) return process.env.GEMINI_API_KEY
  for (const file of [join(ROOT, ".env.local"), join(homedir(), "projects/plocka/apps/web/.env.local")]) {
    if (!existsSync(file)) continue
    const match = readFileSync(file, "utf8").match(/^GEMINI_API_KEY=(.+)$/m)
    if (match) return match[1].trim().replace(/^["']|["']$/g, "")
  }
  throw new Error("No GEMINI_API_KEY found.")
}

/** Inline image item; mime type sniffed from the bytes (Gemini PNGs are often JPEG). */
function imageItem(path) {
  const data = readFileSync(resolve(path))
  const mime = data[0] === 0x89 ? "image/png" : data[0] === 0xff ? "image/jpeg" : "image/webp"
  return { type: "image", data: data.toString("base64"), mime_type: mime }
}

/** Find the first video content item anywhere in the response. */
function findVideo(node) {
  if (!node || typeof node !== "object") return null
  if (node.type === "video" && (node.uri || node.data)) return node
  for (const value of Object.values(node)) {
    const found = findVideo(value)
    if (found) return found
  }
  return null
}

async function api(path, key, init = {}) {
  const response = await fetch(path.startsWith("http") ? path : `${API}${path}`, {
    ...init,
    headers: { "x-goog-api-key": key, "content-type": "application/json", ...(init.headers ?? {}) },
  })
  return response
}

async function generateOne(body, key, file) {
  const response = await api("/interactions", key, { method: "POST", body: JSON.stringify(body) })
  const json = await response.json()
  if (!response.ok) throw new Error(`${response.status} ${json.error?.status ?? ""}: ${json.error?.message ?? JSON.stringify(json).slice(0, 400)}`)

  // Keep the interaction ID so a follow-up turn can edit this video in place.
  if (json.id) writeFileSync(file.replace(/\.mp4$/, ".interaction.txt"), json.id)
  const video = findVideo(json)
  if (!video) {
    writeFileSync(`${file}.response.json`, JSON.stringify(json, null, 2))
    throw new Error(`No video in the response (saved to ${file.replace(ROOT + "/", "")}.response.json).`)
  }
  if (video.data) {
    writeFileSync(file, Buffer.from(video.data, "base64"))
    return
  }

  // URI delivery: wait for the file to become ACTIVE, then download it.
  const id = video.uri.match(/files\/([^:/?]+)/)?.[1]
  for (let i = 0; id && i < 60; i++) {
    const meta = await (await api(`/files/${id}`, key)).json()
    if (meta.state === "ACTIVE") break
    if (meta.state === "FAILED") throw new Error("The video file failed to process.")
    await new Promise((r) => setTimeout(r, 5000))
  }
  const download = await api(video.uri, key, { redirect: "follow" })
  if (!download.ok) throw new Error(`Download failed: ${download.status}`)
  writeFileSync(file, Buffer.from(await download.arrayBuffer()))
}

async function main() {
  const { values } = parseArgs({
    options: {
      name: { type: "string" },
      from: { type: "string" },
      prompt: { type: "string" },
      loop: { type: "boolean", default: false },
      duration: { type: "string", default: "8" },
      resolution: { type: "string", default: "720p" },
      aspect: { type: "string", default: "16:9" },
      count: { type: "string", default: "1" },
      // Edit an existing video instead of generating from a still (e.g.
      // relight the day loop for dark mode, keeping every frame's motion).
      edit: { type: "string" },
      // Edit a video this model generated, by its interaction ID (saved next
      // to each take as .interaction.txt). Works where uploads are blocked.
      previous: { type: "string" },
    },
  })
  if (!values.name || !(values.from || values.edit || values.previous) || !values.prompt)
    throw new Error("Needs --name, --prompt and --from (or --edit / --previous).")
  const previousId = values.previous && existsSync(values.previous)
    ? readFileSync(values.previous, "utf8").trim()
    : values.previous

  const input = previousId
    ? values.prompt
    : values.edit
    ? [
        { type: "video", data: readFileSync(resolve(values.edit)).toString("base64"), mime_type: "video/mp4" },
        { type: "text", text: values.prompt },
      ]
    : (() => {
        const start = imageItem(values.from)
        return [start, ...(values.loop ? [start] : []), { type: "text", text: values.prompt }]
      })()
  const body = {
    model: MODEL,
    ...(previousId ? { previous_interaction_id: previousId } : {}),
    input,
    ...(values.edit ? { generation_config: { video_config: { task: "edit" } } } : {}),
    response_format: {
      type: "video",
      // Edits keep the input's length, shape and size.
      ...(values.edit || previousId
        ? {}
        : { aspect_ratio: values.aspect, resolution: values.resolution, duration: `${values.duration}s` }),
      delivery: "uri",
    },
    background: false,
    store: true, // required for URI delivery
    stream: false,
  }

  const key = loadKey()
  mkdirSync(OUT_DIR, { recursive: true })
  const existing = readdirSync(OUT_DIR).filter((f) => f.startsWith(`${values.name}-`) && f.endsWith(".mp4")).length
  const count = Math.max(1, Number(values.count) || 1)

  console.log(`Generating ${count} × ${values.name} (${values.duration}s, ${values.resolution}) with ${MODEL}…`)
  const results = await Promise.allSettled(
    Array.from({ length: count }, (_, i) =>
      generateOne(body, key, join(OUT_DIR, `${values.name}-${existing + i + 1}.mp4`)).then(
        () => `${values.name}-${existing + i + 1}.mp4`
      )
    )
  )
  for (const result of results) {
    console.log(result.status === "fulfilled" ? `  ✓ art/generated/${result.value}` : `  ✗ ${result.reason.message}`)
  }
}

main().catch((error) => {
  console.error(error.message)
  process.exit(1)
})
